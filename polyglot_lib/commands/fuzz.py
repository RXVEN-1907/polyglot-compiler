"""The 'fuzz' command: run a user function under libFuzzer.

A tiny harness defining LLVMFuzzerTestOneInput(const unsigned char *data,
size_t size) is auto-generated; it forwards libFuzzer's input buffer to the
user's --entry function, which must have exactly that signature.  Built with
-fsanitize=fuzzer (clang only - the GCC backend exits 3 with a hint), run
with -runs=N -max_len=64, and crashes are reported with the artifact path.
"""

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from polyglot_lib.backends import CXX_SUFFIXES, common_compile_args
from polyglot_lib.backends import invoke_compiler
from polyglot_lib.commands import command
from polyglot_lib.output import (
    EXIT_FAILURE, EXIT_MISSING_TOOL, EXIT_USAGE, PolyglotError, green, red,
    run_cmd,
)

ORDER = 155

MAX_LEN = 64
DEFAULT_RUNS = 1000
RUN_TIMEOUT = 300

#: libFuzzer artifact name prefixes we surface on a failing run.
ARTIFACT_PREFIXES = ("crash-", "oom-", "timeout-")

HARNESS_TEMPLATE = """\
/* Auto-generated by 'polyglot fuzz': forwards libFuzzer's input buffer to
   %(entry)s.  Compiled together with the target source. */
#include <stddef.h>

int %(entry)s(const unsigned char *data, size_t size);

/* libFuzzer's main looks for the plain C symbol, so the callback needs
   extern "C" linkage under C++ (the entry above keeps C++ linkage). */
#ifdef __cplusplus
extern "C"
#endif
int LLVMFuzzerTestOneInput(const unsigned char *data, size_t size) {
    return %(entry)s(data, size);
}
"""


def find_artifacts(tmpdir):
    """Crash/OOM/timeout artifact files libFuzzer wrote into tmpdir."""
    found = []
    try:
        for f in sorted(Path(tmpdir).iterdir()):
            if f.is_file() and f.name.startswith(ARTIFACT_PREFIXES):
                found.append(f)
    except OSError:
        pass
    return found


def harness_name_for(src):
    """The generated harness must compile in the same language as FILE so
    the entry declaration links (C++ entries keep C++ mangling)."""
    return "fuzz_harness.cpp" if Path(src).suffix in CXX_SUFFIXES \
        else "fuzz_harness.c"


@command("fuzz")
def cmd_fuzz(tc, args):
    src = Path(args.file)
    if not src.exists():
        raise PolyglotError("Source file not found: %s" % src)
    if tc.kind != "clang":
        raise PolyglotError(
            "fuzz uses libFuzzer (-fsanitize=fuzzer), which is clang-only; "
            "the active backend is %s.\nHint: run 'polyglot --compiler clang "
            "fuzz ...'." % (tc.kind or "unknown"), EXIT_MISSING_TOOL)
    if args.runs < 1:
        raise PolyglotError("--runs must be >= 1", EXIT_USAGE)

    corpus = Path(args.corpus) if getattr(args, "corpus", None) else None
    if corpus is not None:
        try:
            corpus.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise PolyglotError("cannot use corpus dir %s: %s" % (corpus, exc))

    tmpdir = tempfile.mkdtemp(prefix="polyglot_fuzz_")
    keep = False          # keep the tempdir (and any artifact) on a crash
    crash = False
    artifacts = []
    rc = None
    try:
        harness = Path(tmpdir) / harness_name_for(src)
        harness.write_text(HARNESS_TEMPLATE % {"entry": args.entry})
        compiler = tc.compiler_for([str(src)])
        extra = common_compile_args(tc, args, [str(src)])
        exe = Path(tmpdir) / "fuzz_out"
        invoke_compiler([compiler] + extra + ["-fsanitize=fuzzer", str(src),
                                              str(harness), "-o", str(exe)],
                        args, what="fuzz harness build")

        cmd = [str(exe), "-artifact_prefix=%s/" % tmpdir,
               "-runs=%d" % args.runs, "-max_len=%d" % MAX_LEN]
        if corpus is not None:
            cmd.append(str(corpus))
        try:
            proc = run_cmd(cmd, capture_output=True, text=True,
                           stdin=subprocess.DEVNULL, timeout=RUN_TIMEOUT)
        except subprocess.TimeoutExpired:
            keep = True
            raise PolyglotError("fuzzing timed out after %ds (tempdir with "
                                "the harness kept at %s)"
                                % (RUN_TIMEOUT, tmpdir), EXIT_FAILURE)
        rc = proc.returncode
        if rc != 0:
            crash = True
            artifacts = find_artifacts(tmpdir)
            keep = True

        payload = {
            "file": str(src),
            "entry": args.entry,
            "backend": tc.kind,
            "runs": args.runs,
            "max_len": MAX_LEN,
            "corpus": str(corpus) if corpus is not None else None,
            "crash": crash,
            "exit_code": rc,
            "artifacts": [str(a) for a in artifacts],
            "harness_dir": tmpdir if keep else None,
        }
        if getattr(args, "json", False):
            print(json.dumps(payload, indent=2))
        elif crash:
            sys.stderr.write((proc.stderr or "")[-4000:])
            for a in artifacts:
                print(red("artifact: %s" % a))
            print(red("CRASH: libFuzzer exited with code %d" % rc))
        else:
            print(green("fuzz: %d run(s) completed, no crashes" % args.runs))
            if corpus is not None:
                print("corpus: %s" % corpus)

        if crash:
            msg = "libFuzzer found a crash"
            if artifacts:
                msg += "; reproducer: %s" % artifacts[0]
            else:
                msg += "; harness kept at %s" % tmpdir
            raise PolyglotError(msg, EXIT_FAILURE)
    finally:
        if keep:
            sys.stderr.write("note: fuzz harness/artifacts kept in %s\n"
                             % tmpdir)
        else:
            shutil.rmtree(tmpdir, ignore_errors=True)


def register(subparsers, global_flags):
    p = subparsers.add_parser(
        "fuzz",
        help="Fuzz a function with libFuzzer (clang only)")
    p.add_argument("file", help="source file containing the fuzz target")
    p.add_argument("--entry", required=True, metavar="FN",
                   help="function to fuzz; it must have the exact signature "
                        "int FN(const unsigned char *data, size_t size) - "
                        "a harness defining LLVMFuzzerTestOneInput is "
                        "generated and compiled together with FILE")
    p.add_argument("--corpus", metavar="DIR",
                   help="corpus directory (created if missing; seeds the "
                        "fuzzer and collects new inputs)")
    p.add_argument("--runs", type=int, default=DEFAULT_RUNS,
                   help="number of fuzzing runs (default: %d)" % DEFAULT_RUNS)
    p.add_argument("--json", action="store_true",
                   help="machine-readable JSON output")
    global_flags.add_common_flags(p, link=True)
