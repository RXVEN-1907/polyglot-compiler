"""The 'completions' command: shell completion scripts (bash/zsh/fish).

The scripts are generated at runtime from the live argparse registry
(polyglot_lib.cli.build_parser), so every registered command and flag -
including ones added later - is completed without touching this file.
"""

import argparse
import re

from polyglot_lib.commands import command

ORDER = 195

SHELLS = ("bash", "zsh", "fish")


# --------------------------------------------------------------------------
# argparse introspection
# --------------------------------------------------------------------------

def _subparsers_action(parser):
    """The add_subparsers action of a built parser (duck-typed lookup)."""
    for action in parser._actions:
        if getattr(action, "choices", None) is not None \
                and callable(getattr(action, "add_parser", None)):
            return action
    raise ValueError("parser has no subcommands registered")


def _options(parser):
    """[(option_strings, takes_value, help, metavar)] for a parser's
    optional arguments; positional arguments are skipped (completion for
    them is left to the shell's default file matching)."""
    out = []
    for action in parser._actions:
        opts = list(getattr(action, "option_strings", []) or [])
        if not opts:
            continue
        help_text = getattr(action, "help", None)
        if help_text in (None, argparse.SUPPRESS):
            help_text = ""
        takes_value = action.nargs != 0
        out.append((opts, takes_value, str(help_text),
                    getattr(action, "metavar", None)))
    return out


def _command_help(sub_action, name):
    """The help= text a subcommand was registered with, for descriptions."""
    for choice in getattr(sub_action, "_choices_actions", []):
        if getattr(choice, "dest", None) == name:
            return getattr(choice, "help", None) or ""
    return ""


def _clean_desc(text, limit=88):
    """Make a help string safe inside shell single quotes / zsh brackets."""
    text = re.sub(r"\s+", " ", str(text or "")).strip()
    text = text.replace("[", "(").replace("]", ")")
    text = text.replace("\\", "/").replace("`", "'")
    if len(text) > limit:
        text = text[:limit - 1].rstrip() + "…"
    return text


def _sq(text):
    """Escape for inside zsh single quotes (RC_QUOTES: '' is a literal ')."""
    return str(text).replace("'", "''")


def _fish_sq(text):
    """Escape for inside fish single quotes (\\' is a literal ')."""
    return str(text).replace("\\", "\\\\").replace("'", "\\'")


def _bash_fn_name(name):
    return "_polyglot_" + re.sub(r"[^A-Za-z0-9]", "_", name)


# --------------------------------------------------------------------------
# bash
# --------------------------------------------------------------------------

def generate_bash(parser):
    """bash script: complete commands, then each command's flags."""
    sub = _subparsers_action(parser)
    cmds = list(sub.choices)
    gflags = " ".join(o for opts, _, _, _ in _options(parser) for o in opts)

    out = [
        "# bash completion for polyglot",
        "# generated by: polyglot completions bash",
        '# install:     eval "$(polyglot completions bash)"',
        "",
        "_polyglot() {",
        '  local cur',
        '  cur="${COMP_WORDS[COMP_CWORD]}"',
        "  COMPREPLY=()",
        '  local i subcmd=""',
        "  for ((i = 1; i < COMP_CWORD; i++)); do",
        '    case "${COMP_WORDS[i]}" in',
        "      %s) subcmd=\"${COMP_WORDS[i]}\"; break ;;" % "|".join(cmds),
        "    esac",
        "  done",
        '  if [ -z "$subcmd" ]; then',
        '    if [[ "$cur" == -* ]]; then',
        "      COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") )" % gflags,
        "    else",
        "      COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") )" % " ".join(cmds),
        "    fi",
        "    return 0",
        "  fi",
        '  case "$subcmd" in',
    ]
    for name in cmds:
        out.append("    %s) %s ;;" % (name, _bash_fn_name(name)))
    out += [
        "  esac",
        "  return 0",
        "}",
        "",
    ]
    for name in cmds:
        flags = " ".join(o for opts, _, _, _ in _options(sub.choices[name])
                         for o in opts)
        out += [
            "%s() {" % _bash_fn_name(name),
            '  if [[ "$cur" == -* ]]; then',
            "    COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") )" % flags,
            "  fi",
            "  return 0",
            "}",
            "",
        ]
    out.append("complete -F _polyglot polyglot")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# zsh
# --------------------------------------------------------------------------

def _zsh_spec(opt, takes_value, desc, metavar):
    spec = opt + ("[%s]" % _clean_desc(desc) if desc else "")
    if takes_value:
        spec += ":%s:" % (metavar or "value")
    return spec


def _zsh_function_block(parser, opener, indent="  "):
    """One zsh _arguments call for `parser`: opener line, then one spec per
    option (backslash-continued except for the last), zsh-quoted once."""
    specs = []
    for opts, takes_value, desc, metavar in _options(parser):
        for o in opts:
            specs.append(_zsh_spec(o, takes_value, desc, metavar))
    lines = ["%s%s \\" % (indent, opener)]
    for i, spec in enumerate(specs):
        cont = " \\" if i < len(specs) - 1 else ""
        # always single-quote the spec: an unquoted [description] would be
        # subject to zsh globbing when the script is sourced
        lines.append("%s'%s'%s" % (indent, _sq(spec), cont))
    return lines


def generate_zsh(parser):
    """zsh script: #compdef header, command list with descriptions, and one
    _arguments block per subcommand."""
    sub = _subparsers_action(parser)
    cmds = list(sub.choices)

    out = [
        "#compdef polyglot",
        "# zsh completion for polyglot",
        "# generated by: polyglot completions zsh",
        '# install:     eval "$(polyglot completions zsh)"   (or put on fpath)',
        "",
        "_polyglot() {",
        '  local curcontext="$curcontext" state line',
        "  typeset -A opt_args",
    ]
    out += _zsh_function_block(parser, "_arguments -C")
    out += [
        "    '1:command:->cmds' \\",
        "    '*::option:->args'",
        "  case $state in",
        "    cmds)",
        "      local -a commands",
        "      commands=(",
    ]
    for name in cmds:
        desc = _clean_desc(_command_help(sub, name))
        out.append("        '%s:%s'" % (_sq(name), _sq(desc)))
    out += [
        "      )",
        "      _describe -t commands 'polyglot command' commands",
        "      ;;",
        "    args)",
        "      case $line[1] in",
    ]
    for name in cmds:
        out.append("        %s) %s ;;" % (_sq(name), _bash_fn_name(name)))
    out += [
        "      esac",
        "      ;;",
        "  esac",
        "}",
        "",
    ]
    for name in cmds:
        out.append("%s() {" % _bash_fn_name(name))
        out += _zsh_function_block(sub.choices[name], "_arguments",
                                   indent="  ")
        out.append("}")
        out.append("")
    out += [
        "# register when this file is eval'd (compinit already loaded);",
        "# harmless extra registration when autoloaded from fpath.",
        "if (( $+functions[compdef] )); then",
        "  compdef _polyglot polyglot",
        "fi",
    ]
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# fish
# --------------------------------------------------------------------------

def _fish_flags(opts, takes_value):
    parts = []
    for o in opts:
        if o.startswith("--"):
            parts += ["-l", o[2:]]
        elif len(o) == 2:
            parts += ["-s", o[1:]]
    if takes_value:
        parts.append("-r")
    return parts


def _fish_line(cond, opts, takes_value, desc, name=None):
    parts = ["complete", "-c", "polyglot", "-n", cond]
    if name is not None:
        parts += ["-a", "'%s'" % _fish_sq(name)]
    parts += _fish_flags(opts, takes_value)
    if desc:
        parts += ["-d", "'%s'" % _fish_sq(_clean_desc(desc))]
    return " ".join(parts)


def generate_fish(parser):
    """fish script: complete -c polyglot lines for commands and flags."""
    sub = _subparsers_action(parser)

    out = [
        "# fish completion for polyglot",
        "# generated by: polyglot completions fish",
        "# install:     polyglot completions fish | source",
        "",
    ]
    for opts, takes_value, desc, _ in _options(parser):
        out.append(_fish_line("'__fish_use_subcommand'", opts, takes_value,
                              desc))
    for name in sub.choices:
        out.append(_fish_line("'__fish_use_subcommand'", [], False,
                              _command_help(sub, name), name=name))
    out.append("")
    for name, sub_p in sub.choices.items():
        cond = "'__fish_seen_subcommand_from %s'" % name
        for opts, takes_value, desc, _ in _options(sub_p):
            out.append(_fish_line(cond, opts, takes_value, desc))
        out.append("")
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# command
# --------------------------------------------------------------------------

@command("completions", toolchain=False)
def cmd_completions(tc, args):
    from polyglot_lib.cli import build_parser  # lazy: avoids import cycle
    generators = {"bash": generate_bash, "zsh": generate_zsh,
                  "fish": generate_fish}
    print(generators[args.shell](build_parser()), end="")


def register(subparsers, global_flags):
    p = subparsers.add_parser(
        "completions", help="Emit shell completion scripts (bash/zsh/fish)",
        description="Generate a completion script for SHELL from the live "
                    "command registry, so newly registered commands and "
                    "flags are completed automatically.",
        epilog="install with:  eval \"$(polyglot completions bash)\"   |   "
               "zsh: eval \"$(polyglot completions zsh)\"   |   "
               "fish: polyglot completions fish | source")
    p.add_argument("shell", choices=list(SHELLS), help="target shell")
